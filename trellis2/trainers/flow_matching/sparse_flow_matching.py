"""稀疏 flow matching 训练器（结构化稀疏张量版）。

职责：与 flow_matching.py 目标完全一致，但样本是 sp.SparseTensor（feats + 坐标/layout），
加噪与损失都只作用在 feats 上，坐标结构保持不变；per-sample loss 用 x_0.layout 切分。
输入：x_0 为稀疏张量 [N x ... x C]；输出：terms['loss'] 及按时间桶统计的 mse。
契约：噪声必须通过 x_0.replace(...) 生成以共享同一套坐标；稀疏下采样默认步数更少（快照 12 步）。
"""

